-- Monthly RANGE partitions for the append-only, high-volume tables (docs/database-design.md §5).
-- Their primary keys already include the timestamp and they have no foreign keys, as partitioning requires.
-- p_before holds anything older than the first month; pmax holds anything newer than the last, so an
-- insert never fails for lack of a partition. scripts/partition-maintenance.js keeps months ahead
-- (splitting pmax) and drops expired months, using a separate database user.
-- On a large existing table this ALTER rebuilds it; use an online schema-change tool there.

